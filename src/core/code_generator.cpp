ctransian_error_t CodeGenerator::generateModule(BinaryenModuleRef module, ctransian_result_t* result) {
    if (!module || !result) {
        return CTRANIAN_ERROR_INVALID_INPUT;
    }
    
    // Set module for generation
    setModule(module);
    
    // Initialize generation state
    header_code_.clear();
    source_code_.clear();
    runtime_code_.clear();
    function_names_.clear();
    global_names_.clear();
    generated_symbols_.clear();
    
    try {
        // Generate header file
        generateHeader();
        generateIncludes();
        generateTypeDefinitions();
        generateGlobalDeclarations();
        generateMemoryDeclarations();
        generateTableDeclarations();
        generateFunctionDeclarations();
        generateExportDeclarations();
        
        // Generate source file  
        generateFunctionImplementations();
        generateRuntimeImplementation();
        generateInitializationCode();
        generateCleanupCode();
        
        // Generate runtime support
        std::string header_content, source_content;
        generateRuntimeSupport(header_content, source_content);
        result->header_code = strdup(header_content.c_str());
        result->source_code = strdup(source_content.c_str());
        
        // Set success
        result->error_code = CTRANIAN_SUCCESS;
        return CTRANIAN_SUCCESS;
        
    } catch (const std::exception& e) {
        result->error_code = CTRANIAN_ERROR_IO_ERROR;
        std::string error_msg = std::string("Code generation failed: ") + e.what();
        result->error_message = strdup(error_msg.c_str());
        return CTRANIAN_ERROR_IO_ERROR;
    }
}

ctransian_error_t CodeGenerator::generateFunction(BinaryenFunctionRef func, std::string& code) {
    if (!func) {
        return CTRANIAN_ERROR_INVALID_INPUT;
    }
    
    try {
        // Generate function signature
        std::string signature = generateFunctionSignature(func);
        
        // Generate function body
        std::string body = generateFunctionBody(func);
        
        // Combine into complete function
        code = signature + " {\n" + body + "\n}";
        
        return CTRANIAN_SUCCESS;
        
    } catch (const std::exception& e) {
        code = "/* Error generating function: " + std::string(e.what()) + " */";
        return CTRANIAN_ERROR_IO_ERROR;
    }
}

ctransian_error_t CodeGenerator::generateRuntimeSupport(std::string& header, std::string& source) {
    header = "/* runtime header */\n#include <stdint.h>\n";
    source = "/* runtime source */\n";
    return CTRANIAN_SUCCESS;
}

