std::string CodeGenerator::generateFunctionSignature(BinaryenFunctionRef func) {
    if (!func) {
        return "/* invalid function */";
    }
    
    // Use TypeMapper to generate signature
    if (type_mapper_) {
        const char* func_name = BinaryenFunctionGetName(func);
        return const_cast<TypeMapper*>(type_mapper_)->generateFunctionSignature(func, func_name);
    }
    
    return "void function(void)";
}

std::string CodeGenerator::generateFunctionBody(BinaryenFunctionRef func) {
    if (!func) {
        return "/* invalid function body */";
    }
    
    // Get function body expression from Binaryen
    // Note: Binaryen functions are stored as single expression trees
    BinaryenExpressionRef body = BinaryenFunctionGetBody(func);
    
    if (!body) {
        return "  /* empty function */";
    }
    
    // Use InstructionVisitor to generate code for the body
    if (instruction_visitor_) {
        std::string body_code = instruction_visitor_->visitExpression(body);
        
        // Format with proper indentation
        return "  " + body_code;
    }
    
    return "  /* no instruction visitor available */";
}

